"""PyTorch dataset and transforms for the vision modality.

Vision outputs 4 heads (V1-V4), NOT 5 Theta singletons:
  V1: {P}       surface-breaking porosity
  V2: {C}       surface-breaking crack
  V3: {N,U}     surface irregularity present, depth not measurable
  V4: {N,U,L}   surface clean - sound, sub-visible undercut, or internal LOF

PatchDataset is the primary dataset class for training. It reads from
a manifest.csv generated by build_patches.py and supports grouped
splitting by source_image.
"""

from __future__ import annotations

from pathlib import Path

import numpy as np
import pandas as pd
import torch
from PIL import Image
from torch.utils.data import Dataset
from torchvision import datasets, transforms

from weldfusion.frame import class_order, folder_names, vision_head_order


def get_train_transforms(cfg: dict):
    return transforms.Compose(
        [
            transforms.RandomResizedCrop(
                cfg["data"]["image_size"],
                scale=tuple(cfg["augmentation"]["random_resized_crop"]["scale"]),
            ),
            transforms.RandomHorizontalFlip(),
            transforms.RandomRotation(cfg["augmentation"]["rotation_degrees"]),
            transforms.ColorJitter(
                brightness=cfg["augmentation"]["color_jitter"]["brightness"],
                contrast=cfg["augmentation"]["color_jitter"]["contrast"],
                saturation=cfg["augmentation"]["color_jitter"]["saturation"],
            ),
            transforms.ToTensor(),
            transforms.Normalize(
                mean=cfg["normalization"]["mean"],
                std=cfg["normalization"]["std"],
            ),
        ]
    )


def get_eval_transforms(cfg: dict):
    return transforms.Compose(
        [
            transforms.Resize(256),
            transforms.CenterCrop(cfg["data"]["image_size"]),
            transforms.ToTensor(),
            transforms.Normalize(
                mean=cfg["normalization"]["mean"],
                std=cfg["normalization"]["std"],
            ),
        ]
    )


def frame_class_to_idx() -> dict[str, int]:
    """Map processed-folder name -> index in frame order."""
    names = folder_names()
    return {names[c]: i for i, c in enumerate(class_order())}


class FrameImageFolder(datasets.ImageFolder):
    """ImageFolder with class_to_idx forced to frame.yaml order."""

    def find_classes(self, directory):
        folders = folder_names()
        classes = [folders[c] for c in class_order()]
        class_to_idx = {name: i for i, name in enumerate(classes)}
        return classes, class_to_idx


def get_dataloaders(cfg: dict):
    import torch

    train_ds = FrameImageFolder(cfg["data"]["train_dir"], transform=get_train_transforms(cfg))
    val_ds = FrameImageFolder(cfg["data"]["val_dir"], transform=get_eval_transforms(cfg))
    test_ds = FrameImageFolder(cfg["data"]["test_dir"], transform=get_eval_transforms(cfg))

    train_loader = torch.utils.data.DataLoader(
        train_ds,
        batch_size=cfg["data"]["batch_size"],
        shuffle=True,
        num_workers=cfg["data"]["num_workers"],
    )
    val_loader = torch.utils.data.DataLoader(
        val_ds,
        batch_size=cfg["data"]["batch_size"],
        shuffle=False,
        num_workers=cfg["data"]["num_workers"],
    )
    test_loader = torch.utils.data.DataLoader(
        test_ds,
        batch_size=cfg["data"]["batch_size"],
        shuffle=False,
        num_workers=cfg["data"]["num_workers"],
    )
    return train_loader, val_loader, test_loader


# --------------------------------------------------------------------------- #
# PatchDataset for head-based training (V1-V4)
# --------------------------------------------------------------------------- #


def get_patch_train_transforms(image_size: int = 224) -> transforms.Compose:
    """Augmentation transforms for patch training."""
    return transforms.Compose([
        transforms.RandomHorizontalFlip(),
        transforms.RandomVerticalFlip(),
        transforms.RandomRotation(15),
        transforms.ColorJitter(brightness=0.2, contrast=0.2, saturation=0.1),
        transforms.RandomAffine(degrees=0, translate=(0.1, 0.1)),
        transforms.ToTensor(),
        transforms.Normalize(mean=[0.485, 0.456, 0.406], std=[0.229, 0.224, 0.225]),
    ])


def get_patch_eval_transforms(image_size: int = 224) -> transforms.Compose:
    """Evaluation transforms for patch inference."""
    return transforms.Compose([
        transforms.ToTensor(),
        transforms.Normalize(mean=[0.485, 0.456, 0.406], std=[0.229, 0.224, 0.225]),
    ])


class PatchDataset(Dataset):
    """Dataset for vision patches with head labels (V1-V4).

    Reads patches from a manifest CSV generated by build_patches.py.
    Labels are head indices (0-3) corresponding to vision_head_order().

    Parameters
    ----------
    patches_dir : Path
        Directory containing V1/, V2/, V3/, V4/ patch subdirectories.
    manifest_df : pd.DataFrame
        Manifest with columns: patch_path, head, source_image, etc.
    transform : callable, optional
        Image transform. If None, uses eval transforms.
    """

    def __init__(
        self,
        patches_dir: Path | str,
        manifest_df: pd.DataFrame,
        transform: transforms.Compose | None = None,
    ):
        self.patches_dir = Path(patches_dir)
        self.df = manifest_df.reset_index(drop=True)
        self.transform = transform or get_patch_eval_transforms()

        # Map head names to indices
        head_order = vision_head_order()
        self.head_to_idx = {h: i for i, h in enumerate(head_order)}

        # Validate all heads in manifest are known
        unknown_heads = set(self.df["head"].unique()) - set(head_order)
        if unknown_heads:
            raise ValueError(f"Unknown heads in manifest: {unknown_heads}")

    def __len__(self) -> int:
        return len(self.df)

    def __getitem__(self, idx: int) -> tuple[torch.Tensor, int]:
        row = self.df.iloc[idx]
        patch_path = self.patches_dir / row["patch_path"]

        # Load image
        img = Image.open(patch_path).convert("RGB")

        # Apply transforms
        if self.transform:
            img = self.transform(img)

        # Get label (head index)
        label = self.head_to_idx[row["head"]]

        return img, label

    @property
    def labels(self) -> np.ndarray:
        """Return all labels as numpy array (for computing class weights)."""
        return np.array([self.head_to_idx[h] for h in self.df["head"]])

    @property
    def head_names(self) -> tuple[str, ...]:
        """Return ordered head names."""
        return vision_head_order()
